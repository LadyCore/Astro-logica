CREATE DATABASE IF NOT EXISTS astro_logica
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE astro_logica;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  email VARCHAR(255) NOT NULL,
  name VARCHAR(120) NULL,
  password_hash VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY users_email_unique (email)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS natal_charts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NULL,
  subject_name VARCHAR(120) NULL,
  birth_year SMALLINT UNSIGNED NOT NULL,
  birth_month TINYINT UNSIGNED NOT NULL,
  birth_day TINYINT UNSIGNED NOT NULL,
  birth_hour TINYINT UNSIGNED NULL,
  birth_minute TINYINT UNSIGNED NULL,
  time_known TINYINT(1) NOT NULL DEFAULT 1,
  city VARCHAR(160) NOT NULL,
  lat DECIMAL(10, 7) NULL,
  lng DECIMAL(10, 7) NULL,
  tz_str VARCHAR(64) NULL,
  payload_json JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY natal_charts_user_id_index (user_id),
  CONSTRAINT natal_charts_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB;
